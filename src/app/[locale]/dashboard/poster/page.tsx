import { redirect } from "next/navigation";
import { getTranslations, setRequestLocale } from "next-intl/server";
import { MessageCircle, Phone } from "lucide-react";
import { Link } from "@/i18n/navigation";
import { requireUser, publicStorageUrl } from "@/lib/auth";
import { qrSvg, qrTargetUrl } from "@/lib/qr";
import { buttonClass } from "@/components/ui";
import { PrintButton } from "@/components/dashboard/print-button";

export default async function PosterPage({ params }: { params: Promise<{ locale: string }> }) {
  const { locale } = await params;
  setRequestLocale(locale);
  const { profile } = await requireUser(locale);
  if (!profile.onboarded_at || !profile.slug) redirect(`/${locale}/dashboard/onboarding`);
  const t = await getTranslations("poster");
  // Generated by us from the advertiser's slug — safe to inline as SVG for crisp printing.
  const svg = await qrSvg(profile.slug, 1);
  const logo = publicStorageUrl("avatars", profile.logo_path);
  const shortUrl = qrTargetUrl(profile.slug).replace(/^https?:\/\//, "").replace(/\?src=qr$/, "");

  return (
    <div className="min-h-dvh bg-slate-200 py-6 print:bg-white print:py-0">
      <style>{`@page { size: A4; margin: 0 } @media print { html, body { width: 210mm; height: 297mm } }`}</style>
      <div className="mx-auto mb-4 flex w-[210mm] max-w-full justify-between gap-2 px-2 print:hidden">
        <Link href="/dashboard/qr" className={buttonClass("ghost")}>
          {t("back")}
        </Link>
        <PrintButton label={t("print")} />
      </div>

      <article
        className="mx-auto flex h-[297mm] w-[210mm] max-w-full flex-col overflow-hidden bg-white shadow-xl print:shadow-none"
        style={{ printColorAdjust: "exact", WebkitPrintColorAdjust: "exact" }}
      >
        <header className="flex items-center gap-5 bg-navy px-[14mm] py-[10mm] text-white">
          {logo && (
            // eslint-disable-next-line @next/next/no-img-element
            <img src={logo} alt="" className="h-[26mm] w-[26mm] rounded-2xl bg-white object-contain p-1" />
          )}
          <h1 className="text-[11mm] font-bold leading-tight">{profile.display_name}</h1>
        </header>

        <div className="flex flex-1 flex-col items-center justify-center gap-[7mm] px-[14mm] text-center">
          <p className="text-[12mm] font-bold leading-tight text-navy">{t("headline")}</p>
          <div className="rounded-[6mm] border-[1.5mm] border-brand p-[5mm]">
            <div className="h-[118mm] w-[118mm] [&>svg]:h-full [&>svg]:w-full" dangerouslySetInnerHTML={{ __html: svg }} />
          </div>
          <p className="text-[7mm] font-medium text-brand">{t("sub")}</p>
          <p className="text-[5mm] text-slate-500" dir="ltr">
            {shortUrl}
          </p>
        </div>

        <footer className="flex flex-wrap items-center justify-center gap-x-[10mm] gap-y-[3mm] bg-sky-soft px-[14mm] py-[8mm] text-[6mm] font-bold text-navy">
          {profile.phone && (
            <span className="inline-flex items-center gap-[2mm]" dir="ltr">
              <Phone className="h-[6mm] w-[6mm]" aria-hidden /> {profile.phone}
            </span>
          )}
          {profile.whatsapp && profile.whatsapp !== profile.phone && (
            <span className="inline-flex items-center gap-[2mm]" dir="ltr">
              <MessageCircle className="h-[6mm] w-[6mm] text-whatsapp" aria-hidden /> {profile.whatsapp}
            </span>
          )}
        </footer>
      </article>
    </div>
  );
}
